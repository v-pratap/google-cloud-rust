StatusOr<ObjectDescriptor> Client::OpenAndRead(std::string const& bucket,
                                               std::string const& object,
                                               std::uint64_t offset, std::uint64_t length,
                                               ObjectDescriptor::ChunkHandler const& handler,
                                               std::uint64_t* bytes) const {
  ReadContext ctx{&handler, nullptr};
  GcsObjectDescriptor* handle = nullptr;
  std::uint64_t got = 0;
  CStatus status;
  gcs_object_open_and_read(handle_.get(), bucket.c_str(), object.c_str(), offset, length,
                           &ReadTrampoline, &ctx, &handle, &got, status.get());
  if (ctx.error) {
    if (handle) gcs_object_descriptor_free(handle);
    std::rethrow_exception(ctx.error);
  }
  auto s = status.ToStatus();
  if (!s.ok()) return s;
  if (bytes) *bytes = got;
  return ObjectDescriptor(handle);
}

