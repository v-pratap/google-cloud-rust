StatusOr<std::string> ObjectDescriptor::ReadToString(std::uint64_t offset,
                                                     std::uint64_t length) const {
  std::string out;
  if (length != 0) out.reserve(length);
  auto r = Read(offset, length, [&](std::uint8_t const* d, std::size_t n) {
    out.append(reinterpret_cast<char const*>(d), n);
    return true;
  });
  if (!r.ok()) return r.status();
  return out;
}

