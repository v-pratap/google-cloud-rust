StatusOr<Client> Client::Create(Options const& options) {
  GcsClientOptions c_opts{};
  c_opts.endpoint = options.endpoint.empty() ? nullptr : options.endpoint.c_str();
  c_opts.grpc_subchannel_count = options.grpc_subchannel_count;
  c_opts.worker_threads = options.worker_threads;

  GcsClient* handle = nullptr;
  CStatus status;
  if (gcs_client_new(&c_opts, &handle, status.get()) != 0) return status.ToStatus();
  return Client(handle);
}

