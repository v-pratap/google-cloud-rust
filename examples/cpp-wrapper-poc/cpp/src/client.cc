/// RAII holder for the C status; converts it to a C++ Status.
class CStatus {
 public:
  CStatus() = default;
  CStatus(CStatus const&) = delete;
  CStatus& operator=(CStatus const&) = delete;
  ~CStatus() { gcs_status_clear(&s_); }

  GcsStatus* get() { return &s_; }

  Status ToStatus() const {
    if (s_.code == 0) return {};
    return Status(static_cast<StatusCode>(s_.code),
                  s_.message ? s_.message : "");
  }

 private:
  GcsStatus s_{0, nullptr};
};

std::string ToString(char const* s) { return s ? std::string(s) : std::string(); }

ObjectMetadata FromC(GcsObjectMetadata const& m) {
  ObjectMetadata r;
  r.bucket = ToString(m.bucket);
  r.name = ToString(m.name);
  r.storage_class = ToString(m.storage_class);
  r.size = m.size;
  r.generation = m.generation;
  r.metageneration = m.metageneration;
  return r;
}

/// Owns C metadata strings for the duration of a call.
struct CMetadata {
  GcsObjectMetadata m{nullptr, nullptr, nullptr, 0, 0, 0};
  ~CMetadata() { gcs_object_metadata_clear(&m); }
};

// --- Callback trampolines --------------------------------------------------
// C++ exceptions must never unwind into Rust (that is undefined behaviour), so
// each trampoline catches everything, stashes it, and tells Rust to stop.

struct ReadContext {
  ObjectDescriptor::ChunkHandler const* handler;
  std::exception_ptr error;
};

extern "C" bool ReadTrampoline(void* user, std::uint8_t const* data,
                               std::size_t len) {
  auto* ctx = static_cast<ReadContext*>(user);
  try {
    return (*ctx->handler)(data, len);
  } catch (...) {
    ctx->error = std::current_exception();
    return false;
  }
}

struct ListContext {
  std::function<bool(ObjectMetadata const&)> const* handler;
  std::exception_ptr error;
};

extern "C" bool ListTrampoline(void* user, GcsObjectMetadata const* m) {
  auto* ctx = static_cast<ListContext*>(user);
  try {
    return (*ctx->handler)(FromC(*m));
  } catch (...) {
    ctx->error = std::current_exception();
    return false;
  }
}

