StatusOr<std::uint64_t> Client::ReadObject(
    std::string const& bucket, std::string const& object,
    ObjectDescriptor::ChunkHandler const& handler) const {
  ReadContext ctx{&handler, nullptr};
  std::uint64_t bytes_read = 0;
  CStatus status;
  gcs_read_object(handle_.get(), bucket.c_str(), object.c_str(), &ReadTrampoline, &ctx,
                  &bytes_read, status.get());
  if (ctx.error) std::rethrow_exception(ctx.error);
  auto s = status.ToStatus();
  if (!s.ok()) return s;
  return bytes_read;
}

