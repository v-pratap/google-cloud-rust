StatusOr<std::uint64_t> ObjectDescriptor::ReadRanges(
    std::vector<std::pair<std::uint64_t, std::uint64_t>> const& ranges,
    RangeChunkHandler const& handler) const {
  std::vector<std::uint64_t> offs, lens;
  offs.reserve(ranges.size());
  lens.reserve(ranges.size());
  for (auto const& [o, l] : ranges) {
    offs.push_back(o);
    lens.push_back(l);
  }
  RangesContext ctx{&handler, nullptr};
  std::uint64_t total = 0;
  CStatus status;
  gcs_object_read_ranges(handle_.get(), offs.data(), lens.data(), ranges.size(),
                         &RangesTrampoline, &ctx, &total, status.get());
  if (ctx.error) std::rethrow_exception(ctx.error);
  auto s = status.ToStatus();
  if (!s.ok()) return s;
  return total;
}

